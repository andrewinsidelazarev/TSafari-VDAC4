/* Картинки на странице (<img>).
 *
 * КАК КАРТИНКА ПОПАДАЕТ НА ЭКРАН.
 *   1. Разбор HTML (html.c) встречает <img src=…>: image_add заводит запись картинки (по адресу —
 *      одна на страницу, сколько бы раз она ни стояла) и даёт размер места под неё. Место стоит в
 *      строке как встроенный блок (doc_inline), и когда строка легла на страницу, image_place
 *      запоминает, где оно.
 *   2. Пока картинки нет, на её месте в странице рисуется заглушка (image_paint, дизайн Codex 08b):
 *      плашка со значком, «Loading image…» или «Image unavailable».
 *   3. После страницы app.c грузит картинки по одной (image_next — сначала видимые) и отдаёт
 *      пришедшие байты image_loaded: JPEG и PNG раскладывает в память видеочипа сопроцессор BL616
 *      (с прошивки 39 — CMD_LOADIMAGE_BOX, сразу в размер места; старая — CMD_LOADIMAGE, как у
 *      FT812), GIF — сам ESP32 (gif.c), WebP — библиотека libwebp на ESP32.
 *   4. Готовая картинка рисуется не в странице, а поверх неё, отдельным битмапом в дисплей-листе
 *      (image_dl): видеочип сам растягивает или сжимает её до размера места.
 *   Размер картинки без width и height в HTML узнаётся только после загрузки — тогда страницу
 *   раскладывают заново (app.c), картинки при этом остаются в памяти (image_layout_begin).
 *
 * ПАМЯТЬ ВИДЕОЧИПА. Картинки лежат в RAM_G с 0x114000 до конца 2 МБ (~940 КБ; ниже — кольцо
 * страницы, палитры, интерфейс, маски списков форм). Это кэш вокруг видимой части: когда места
 * не хватает ближней картинке, дальняя убирается, а её файл остаётся в PSRAM, и при прокрутке
 * обратно она раскладывается снова без сети. Видимые картинки не убираются. */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include "ft.h"

#define IMAGE_ID_BASE 0x40000000         /* номер встроенного блока картинки = это + номер места */

/* Новая страница: забыть все картинки и освободить их память видеочипа. */
void image_clear(void);
/* Та же страница раскладывается заново: места — заново, загруженные картинки остаются. */
void image_layout_begin(void);
/* <img>: полный адрес url, подпись alt (может быть NULL), ширина и высота из атрибутов (0 — нет),
 * ширина места max_w. В *w, *h — размер блока в строке. create = 0 — только размер (измерение
 * ячеек таблицы); иначе — номер места для doc_inline (IMAGE_ID_BASE + …) или −1. link — номер
 * ссылки, внутри которой картинка (−1 — нет): щелчок по картинке — переход. */
int image_add(const char *url, const char *alt, int attr_w, int attr_h, int max_w, int link, int create,
              int *w, int *h);
/* Строка с местом id легла на страницу: левый верхний угол (x, y), фон под ним bg. */
void image_place(int id, int x, int y, uint32_t bg);
/* Фон-картинка коробки CSS (background-image): как её уложить в коробку. */
typedef struct {
    uint8_t size;                        /* background-size: 'a' auto, 'c' cover, 'n' contain, 'l' — w × h */
    uint8_t wp, hp, xp, yp;              /* w, h, x, y — проценты (иначе точки) */
    int w, h;                            /* размер при 'l'; −1 — auto */
    int x, y;                            /* background-position: где картинка в коробке */
} image_bg_t;
/* Место фона-картинки (прямоугольник — потом, image_back_set): заводится, когда коробка
 * открывается, — раньше картинок внутри неё, поэтому рисуется под ними. Номер места или −1. */
int image_back_add(const char *url, const image_bg_t *bg);
/* Коробка закрылась: прямоугольник внутри рамки. В коробке есть текст — фон-картинку не рисовать
 * (картинки ложатся поверх страницы и закрыли бы его; остаётся цвет фона). */
void image_back_set(int id, int x, int y, int w, int h, int has_text);
/* Заглушка места id в странице (зовёт page.c при отрисовке строк). */
void image_paint(int id, int x, int y, int w, int h, uint32_t bg);
/* Готовые картинки видимой части (top — прокрутка) — в дисплей-лист поверх страницы. */
void image_dl(ft_dl_t *d, int top);
/* Прокрутка сейчас (top): звать на каждом шаге браузера — по ней решается, какие картинки далеко. */
void image_view(int top);
/* Адрес следующей картинки для загрузки (сначала те, что видны с прокрутки top); NULL — нечего.
 * Убранную из RAM_G картинку, чей файл остался в PSRAM, раскладывает снова сама (без сети). */
const char *image_next(int top);
/* Пришли байты картинки url (body = NULL — не загрузилась). Буфер body (PSRAM) image.c забирает
 * себе: хранит или освобождает. cache: 0 — не записывать в кэш на карте (imgcache.h); 1 — из сети:
 * когда картинка разобрана, записать её в кэш (WebP, GIF, SVG — точками экрана, JPEG и PNG —
 * файлом); 2 — из сети по «обновить» или взамен негодного: записать заново; 3 — файл с карты: если
 * его разбирает ESP32 (файл от прежней версии), записать вместо него точки.
 * 1 — её размер меняет раскладку страницы (в HTML размер не был задан): страницу пора разложить
 * заново. */
int image_loaded(const char *url, uint8_t *body, size_t len, int cache);
/* Пришли с карты точки экрана картинки url (кэш, IMGCACHE_PIX: заголовок и точки, буфер blob
 * image.c забирает): сразу в RAM_G, без разбора. −1 — не подходят месту на странице (оно другого
 * размера) или испорчены: брать из сети (и записать в кэш заново); иначе — как у image_loaded. */
int image_cached(const char *url, uint8_t *blob, size_t len);
/* Картинка url, которую сейчас грузят, ушла от видимой части (прокрутка top) дальше двух экранов:
 * её загрузку лучше бросить — она держит видимые (картинки идут по одной). */
int image_far(const char *url, int top);
/* Загрузку картинки url бросили (image_far): она снова ждёт и загрузится, когда подойдёт. */
void image_requeue(const char *url);
/* Пул картинок в RAM_G: до 3 МБ (three_mb = 1, после ft_ramg_3mb) или до 2 МБ. Звать до картинок. */
void image_pool(int three_mb);
/* 1 — картинка стала готова или пропала: нужен новый дисплей-лист (флаг снимается). */
int image_changed(void);
/* Больше не грузить (кнопка «стоп»): незагруженные остаются заглушками. */
void image_stop(void);
/* Фоновая задача разбора GIF, WebP и SVG (ядро 1, приоритет 0): запустить при старте браузера.
 * 0 — не вышло (тогда эти картинки не разбираются). */
int image_init(void);
/* Фоновая задача вышла (после ts_running = 0) — код можно выгружать. */
int image_stopped(void);
/* Звать на каждом шаге браузера: фоновый разбор кончился — точки в RAM_G (или картинка ждёт места).
 * 1 — её размер меняет раскладку страницы (как у image_loaded). */
int image_poll(void);
#ifdef TSAFARI_HOST
/* Стенд: из мест картинок, видимых при прокрутке top, — сколько всего, готовых и недоступных;
 * *used — сколько байт пула RAM_G занято. */
void image_host_stats(int top, int *seen, int *ready, int *failed, uint32_t *used);
/* Стенд: размер первого места картинки, адрес которой кончается на tail; 0 — такой нет. */
int image_host_size(const char *tail, int *w, int *h);
/* Стенд: где первое место такой картинки на странице и его размер; 0 — такой нет. */
int image_host_rect(const char *tail, int *x, int *y, int *w, int *h);
#endif
