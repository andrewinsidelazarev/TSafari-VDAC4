/* Картинки на странице (<img>).
 *
 * КАК КАРТИНКА ПОПАДАЕТ НА ЭКРАН.
 *   1. Разбор HTML (html.c) встречает <img src=…>: image_add заводит запись картинки (по адресу —
 *      одна на страницу, сколько бы раз она ни стояла) и даёт размер места под неё. Место стоит в
 *      строке как встроенный блок (doc_inline), и когда строка легла на страницу, image_place
 *      запоминает, где оно.
 *   2. Пока картинки нет, на её месте в странице рисуется заглушка (image_paint, дизайн Codex 08b):
 *      плашка со значком, «Loading image…» или «Image unavailable».
 *   3. После страницы app.c грузит картинки по одной (image_next — сначала видимые) и отдаёт
 *      пришедшие байты image_loaded: JPEG и PNG раскладывает в память видеочипа сопроцессор BL616
 *      (команда CMD_LOADIMAGE — те же правила, что у FT812), GIF — сам ESP32 (gif.c).
 *   4. Готовая картинка рисуется не в странице, а поверх неё, отдельным битмапом в дисплей-листе
 *      (image_dl): видеочип сам растягивает или сжимает её до размера места.
 *   Размер картинки без width и height в HTML узнаётся только после загрузки — тогда страницу
 *   раскладывают заново (app.c), картинки при этом остаются в памяти (image_layout_begin).
 *
 * ПАМЯТЬ ВИДЕОЧИПА. Картинки лежат в RAM_G с 0x114000 до конца 2 МБ (~940 КБ; ниже — кольцо
 * страницы, палитры, интерфейс, маски списков форм). Места нет — картинка «недоступна». */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include "ft.h"

#define IMAGE_ID_BASE 0x40000000         /* номер встроенного блока картинки = это + номер места */

/* Новая страница: забыть все картинки и освободить их память видеочипа. */
void image_clear(void);
/* Та же страница раскладывается заново: места — заново, загруженные картинки остаются. */
void image_layout_begin(void);
/* <img>: полный адрес url, подпись alt (может быть NULL), ширина и высота из атрибутов (0 — нет),
 * ширина места max_w. В *w, *h — размер блока в строке. create = 0 — только размер (измерение
 * ячеек таблицы); иначе — номер места для doc_inline (IMAGE_ID_BASE + …) или −1. link — номер
 * ссылки, внутри которой картинка (−1 — нет): щелчок по картинке — переход. */
int image_add(const char *url, const char *alt, int attr_w, int attr_h, int max_w, int link, int create,
              int *w, int *h);
/* Строка с местом id легла на страницу: левый верхний угол (x, y), фон под ним bg. */
void image_place(int id, int x, int y, uint32_t bg);
/* Заглушка места id в странице (зовёт page.c при отрисовке строк). */
void image_paint(int id, int x, int y, int w, int h, uint32_t bg);
/* Готовые картинки видимой части (top — прокрутка) — в дисплей-лист поверх страницы. */
void image_dl(ft_dl_t *d, int top);
/* Адрес следующей картинки для загрузки (сначала те, что видны с прокрутки top); NULL — нечего. */
const char *image_next(int top);
/* Пришли байты картинки url (body = NULL — не загрузилась). 1 — её размер меняет раскладку
 * страницы (в HTML размер не был задан): страницу пора разложить заново. */
int image_loaded(const char *url, const uint8_t *body, size_t len);
/* 1 — картинка стала готова или пропала: нужен новый дисплей-лист (флаг снимается). */
int image_changed(void);
/* Больше не грузить (кнопка «стоп»): незагруженные остаются заглушками. */
void image_stop(void);
