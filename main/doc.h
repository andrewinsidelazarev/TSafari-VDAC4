/* Раскладка текста: как из потока слов получаются строки на странице.
 *
 * Разбор HTML (html.c) и встроенные страницы (demo.c) не думают о строках и ширине экрана:
 * они просто говорят «вот кусок текста такого-то стиля», «здесь конец абзаца», «здесь отступ».
 * Этот модуль копит текст абзаца, а в конце абзаца режет его на строки по ширине экрана —
 * переносит по словам, как текстовый редактор, — и отдаёт строки странице (page.c).
 *
 * Шрифт моноширинный: каждая буква шириной 12 точек. Поэтому ширину удобно считать в
 * «колонках» — сколько букв помещается в строку: (1024 − 2 · 8) / 12 = 84.
 *
 * «Стиль» — как выглядит кусок текста: цвет букв, цвет фона, подчёркнут ли, ссылка ли. */
#pragma once
#include <stdint.h>

#define DOC_COLS ((1024 - 2 * PAGE_MARGIN) / 12)     /* букв в строке без отступов */

typedef struct {
    uint32_t fg;             /* цвет букв 0xRRGGBB */
    uint32_t bg;             /* цвет фона под буквами; 0 — фон страницы или блока */
    unsigned flags;          /* PAGE_UNDERLINE — подчеркнуть */
    int link;                /* номер ссылки (html.c); −1 — не ссылка */
} doc_style_t;

/* Начать раскладку новой страницы с фоном bg. */
void doc_begin(uint32_t bg);
/* Кусок текста UTF-8 в текущий абзац (пробелы — как есть: схлопывает вызывающий). */
void doc_text(const char *utf8, unsigned bytes, const doc_style_t *style);
/* Конец абзаца: строки — в страницу; дальше — промежуток не меньше gap точек (промежутки
 * подряд не складываются: берётся наибольший). */
void doc_flush(int gap);
/* Отступ слева следующих строк, в колонках (списки, цитаты); 0 — без отступа. */
void doc_indent(int cols);
/* Текущий отступ в колонках (чтобы вернуть его после вложенного списка). */
int doc_get_indent(void);
/* Полоса цвета rgb высотой h на всю ширину (рамки, разделители). */
void doc_rule(uint32_t rgb, int h, int gap);
/* Абзац из кусков разного стиля разом (встроенные страницы). */
void doc_para(const char *const *texts, const doc_style_t *styles, unsigned parts, int gap);
/* Блок с фоном: следующие абзацы до doc_box_end — на нём с отступом. */
void doc_box_begin(uint32_t bg);
/* Конец блока с фоном; дальше — промежуток gap точек. */
void doc_box_end(int gap);
/* Где сейчас низ страницы (куда ляжет следующая строка), в точках. */
int doc_y(void);
/* Абзац ещё пуст (ничего не набрано после doc_flush). */
int doc_empty(void);
