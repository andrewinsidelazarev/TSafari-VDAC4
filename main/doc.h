/* Раскладка текста: как из потока слов получаются строки на странице.
 *
 * Разбор HTML (html.c) и встроенные страницы (demo.c) не думают о строках и ширине экрана:
 * они просто говорят «вот кусок текста такого-то стиля», «здесь конец абзаца», «здесь отступ».
 * Этот модуль копит текст абзаца, а в конце абзаца режет его на строки по ширине — переносит по
 * словам, как текстовый редактор, — и отдаёт строки странице (page.c).
 *
 * Всё считается в точках. Шрифт моноширинный, но размеров (начертаний, font.h) несколько, и в
 * одной строке их можно смешивать: у каждого свой шаг, своя высота и своя базовая линия — линия,
 * на которой «стоят» буквы. Высота строки — по самому высокому начертанию в ней, все буквы
 * строки стоят на общей базовой линии.
 *
 * «Стиль» — как выглядит кусок текста: цвет букв и фона, подчёркнут ли, жирный ли, ссылка ли,
 * каким начертанием. «Встроенный блок» — прямоугольник заданного размера (картинка, поле формы):
 * он стоит в строке как одно слово, а куда он попал, раскладка сообщает тому, кто его вставил.
 *
 * «Рамка» — прямоугольная область, в которую идут строки: сначала это вся страница, а у таблиц —
 * каждая ячейка (doc_frame_push). «Измерение» (doc_measure_push) — та же раскладка, но без вывода:
 * только узнать, какой ширины получается текст (нужно, чтобы разделить ширину таблицы между
 * столбцами). */
#pragma once
#include <stdint.h>
#include "page.h"

/* Ширина текста основного начертания на странице без отступов. */
#define DOC_WIDTH (1024 - 2 * PAGE_MARGIN)

enum { DOC_LEFT, DOC_CENTER, DOC_RIGHT };

typedef struct {
    uint32_t fg;             /* цвет букв 0xRRGGBB */
    uint32_t bg;             /* цвет фона под буквами; 0 — фон страницы, блока или ячейки */
    unsigned flags;          /* PAGE_UNDERLINE — подчеркнуть, PAGE_BOLD — жирный */
    int link;                /* номер ссылки (html.c); −1 — не ссылка */
    unsigned face;           /* начертание FACE_… (font.h); 0 — основной текст 20 px */
} doc_style_t;

/* Начать раскладку новой страницы с фоном bg. */
void doc_begin(uint32_t bg);
/* Кусок текста UTF-8 в текущий абзац (пробелы — как есть: схлопывает вызывающий). */
void doc_text(const char *utf8, unsigned bytes, const doc_style_t *style);
/* Встроенный блок w×h точек с номером id в текущий абзац. Когда строка с ним ляжет на страницу,
 * раскладка вызовет place(id, x, y) — левый верхний угол блока. desc — сколько точек блока
 * ниже базовой линии строки (у поля формы — чтобы текст в поле стоял на одной линии с текстом
 * рядом); 0 — низ блока на базовой линии. */
void doc_inline(int w, int h, int desc, int id);
void doc_set_inline_cb(void (*place)(int id, int x, int y));
/* Конец абзаца: строки — в страницу; дальше — промежуток не меньше gap точек (промежутки
 * подряд не складываются: берётся наибольший). */
void doc_flush(int gap);
/* Выравнивание следующих строк (DOC_LEFT, DOC_CENTER, DOC_RIGHT) — до следующего вызова. */
void doc_align(int align);
int doc_get_align(void);
/* Цвет фона там, куда сейчас ложатся строки (блок, ячейка или страница). */
uint32_t doc_bg(void);
/* Первая строка следующего абзаца начинается на px точек левее отступа (маркер пункта списка
 * «висит» слева, а перенесённые строки идут ровно под текстом пункта). */
void doc_hang(int px);
/* Фон всей страницы (<body bgcolor>), пока на ней ничего не нарисовано. */
void doc_set_bg(uint32_t bg);
/* Отступ слева следующих строк, в точках (списки, цитаты); 0 — без отступа. */
void doc_indent(int px);
int doc_get_indent(void);
/* Полоса цвета rgb высотой h на всю ширину (рамки, разделители). */
void doc_rule(uint32_t rgb, int h, int gap);
/* Абзац из кусков разного стиля разом (встроенные страницы). */
void doc_para(const char *const *texts, const doc_style_t *styles, unsigned parts, int gap);
/* Блок с фоном bg: следующие абзацы до doc_box_end — на нём, с отступами pad_x слева и справа
 * и pad_y сверху и снизу; bar ≠ 0 — черта этого цвета в 3 точки у левого края (цитата).
 * 0 — блок не открыт (в этой рамке уже открыт другой: блоки в одной рамке не вкладываются). */
int doc_box_begin(uint32_t bg, int pad_x, int pad_y, uint32_t bar);
/* Конец блока с фоном; дальше — промежуток gap точек. */
void doc_box_end(int gap);
/* Где сейчас низ (куда ляжет следующая строка), в точках. */
int doc_y(void);
/* Левый край и ширина места для строк в текущей рамке (с отступом и полями блока). */
int doc_x(void);
int doc_width(void);
/* Абзац ещё пуст (ничего не набрано после doc_flush). */
int doc_empty(void);
/* Дальше — не выше y (после таблицы): строки текущей рамки пойдут с этого места. */
void doc_skip_to(int y);

/* Рамка: следующие строки — в прямоугольник шириной w с левым краем x, сверху вниз от y; bg —
 * её фон (под сглаживание букв; 0 — как у той, что снаружи). doc_frame_pop — вернуться в прежнюю
 * рамку; возвращает, где кончились строки этой. */
void doc_frame_push(int x, int w, int y, uint32_t bg);
int doc_frame_pop(void);

/* Измерение: всё до doc_measure_pop не выводится, а только меряется. min — самое длинное
 * неразрывное (слово, встроенный блок), max — самая длинная строка, если её не переносить.
 * Измерения бывают вложенными (таблица в ячейке таблицы). doc_measure_add — добавить готовые
 * размеры (вложенная таблица). doc_measuring — 1, если сейчас идёт измерение. */
void doc_measure_push(void);
void doc_measure_pop(int *min_w, int *max_w);
void doc_measure_add(int min_w, int max_w);
int doc_measuring(void);
