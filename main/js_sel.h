/* Селекторы для скриптов: querySelector, querySelectorAll, matches, closest — по дереву dom.c.
 *
 * Свой разбор, не css.c: тому хватает того, что нужно таблицам стилей (и он выбрасывает правила,
 * которые к странице не подойдут), а скриптам нужны и соседи («+», «~»), и номера среди братьев
 * (:nth-child), и :not(), и атрибуты у предков. Селектор, которого мы не понимаем (:has(), ::before
 * в querySelector), — синтаксическая ошибка, как у браузера на неверный селектор: jQuery тогда ищет
 * сам, своими средствами. */
#pragma once
#include <stddef.h>
#include "dom.h"

/* Разобрать селектор (список через запятую). 0 — ошибка (текст не тот или мы такое не умеем).
 * Разобранный живёт до следующего js_sel_compile. */
int js_sel_compile(const char *s, size_t n);
/* Подходит ли элемент e к последнему разобранному селектору; scope — элемент, у которого
 * вызвали поиск (для :scope), 0 — документ. */
int js_sel_match(dom_id e, dom_id scope);
/* Найти внутри root (без него самого) подходящие элементы по порядку документа: номера — в out
 * (не больше max); возвращает, сколько нашлось всего (может быть больше max). first — только
 * первый. */
size_t js_sel_find(dom_id root, int first, dom_id *out, size_t max);
