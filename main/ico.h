/* Значки ICO (favicon сайтов, у DuckDuckGo — external-content.duckduckgo.com/ip3/сайт.ico).
 *
 * ICO — «папка» из нескольких картинок одного значка разных размеров (16×16, 32×32, 48×48…).
 * В начале файла — оглавление: сколько картинок, у каждой ширина, высота, где лежит и сколько
 * байт. Сама картинка — либо PNG целиком (её разбирает BL616, как обычный PNG), либо картинка BMP
 * без своего заголовка файла: заголовок BITMAPINFOHEADER, палитра, точки строками снизу вверх и
 * за ними «маска И» — по биту на точку, 1 = прозрачно. Её раскладывает ESP32 (ico.c). */
#pragma once
#include <stddef.h>
#include <stdint.h>

/* Это ICO (значок 00 00 01 00 или курсор 00 00 02 00)? */
int ico_is(const uint8_t *p, size_t n);
/* Выбрать картинку из оглавления под место want точек (0 — место по картинке: самую большую):
 * самую маленькую не меньше want, а таких нет — самую большую; при равном размере — с большим
 * числом цветов. *off, *size — где она в файле; *png — 1, если внутри PNG. 0 — годной нет. */
int ico_pick(const uint8_t *p, size_t n, int want, uint32_t *off, uint32_t *size, int *png);
/* Размер картинки BMP из ICO (d — её байты, n — сколько). 0 — не BMP или такую не разбираем. */
int ico_bmp_size(const uint8_t *d, size_t n, int *w, int *h);
/* Разложить картинку BMP в точки видеочипа размером tw × th (меньше своего — усредняя, больше не
 * бывает): с прозрачностью — ARGB4 (*alpha = 1), без — RGB565. *pix — память ts_alloc
 * (освобождает вызвавший), байт — tw × th × 2 с дополнением до слова. 0 — испорчена; −1 — нет памяти. */
int ico_bmp_decode(const uint8_t *d, size_t n, int tw, int th, uint16_t **pix, int *alpha);
