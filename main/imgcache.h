/* Кэш картинок на карте Evo: папка Cache\Images рядом с TSAFARI.SPG (решение пользователя 07.11).
 *
 * ЗАЧЕМ. Картинка, пришедшая из сети, остаётся на карте, и в следующий раз (та же страница
 * завтра, другая страница с тем же логотипом, картинка, убранная из памяти при прокрутке)
 * браузер берёт её с карты, а не из сети.
 *
 * КАК. ESP32 до карты не достаёт: читать и писать её умеет только программа Z80 (TSAFARI.SPG,
 * launcher/imgcache.asm) через драйвер FAT32. Браузер шлёт ей событие E8 — что сделать, она
 * делает и докладывает (обмен — в начале launcher/imgcache.asm):
 *   при запуске браузера — список файлов папки (имена, размеры, время);
 *   картинка нужна, и она в кэше — прочитать файл и прислать его кусками;
 *   картинка пришла из сети — записать её файлом (кусками, как скачанный файл, download.c);
 *   кэш больше 100 МБ — удалить самый старый файл (кольцо: старые по времени уходят первыми).
 * Время файлу ставит программа Z80 по часам Evo — как скачанным файлам.
 *
 * ИМЕНА. Файл картинки называется по её адресу: из адреса считается 40-битная «свёртка» (хеш
 * FNV-1a), она записывается восемью знаками 0–9, A–V, и к ней — «.IMG» (например 0K3F9QAB.IMG).
 * Короткие имена 8.3 драйвер пишет без длинных записей каталога — так быстрее и надёжнее. В
 * начале файла — заголовок с самим адресом: если у двух адресов свёртка совпала, чужой файл
 * не подсунется (он просто не подойдёт, и картинка пойдёт из сети).
 *
 * ЧТО В ФАЙЛЕ (решение пользователя 07.11: «в кэше лучше хранить уже сжатыми под формат экрана,
 * чтобы не пережимать каждый раз»). Картинку, которую раскладывает сам ESP32 (WebP, GIF, SVG —
 * секунды, WebP 2560×2560 — ~10 с), кэш хранит готовыми точками экрана (IMGCACHE_PIX): с карты —
 * и сразу в видеочип, без разбора; у большой фотографии точки ещё и меньше файла (слайдер
 * zx-evolution.com: 354 КБ вместо 1,2 МБ). JPEG и PNG раскладывает BL616 прямо в память видеочипа
 * за доли секунды, а прочитать точки оттуда ESP32 может только по слову — их кэш хранит файлом
 * (IMGCACHE_FILE), он и меньше точек.
 *
 * Картинка нужна, а она в кэше, — берётся с карты, даже если кэш занят: идущая запись прерывается
 * (ответ «хватит», недописанный файл удалится) и повторится после чтения — видимая картинка важнее
 * будущих заходов. Из сети — если её нет в кэше, идёт загрузка файла на карту или кэша нет (старая
 * TSAFARI.SPG). «Обновить» (F5) берёт картинки из сети и записывает их в кэш заново. */
#pragma once
#include <stddef.h>
#include <stdint.h>

/* Начать: запросить у программы Z80 список файлов кэша (задача браузера, при запуске). */
void imgcache_init(void);
/* Раз в проход цикла браузера: события программе Z80, сроки, следующая запись или удаление. */
void imgcache_tick(uint32_t now);
/* Что лежит в файле кэша: файл картинки или точки экрана (их заголовок — у image.c). */
#define IMGCACHE_FILE 0
#define IMGCACHE_PIX  1
/* Начать чтение картинки url с карты (идущая запись прерывается и повторится потом). 1 — начато
 * (итог — imgcache_read_poll); 0 — её нет в кэше, кэш не готов или идёт загрузка файла на карту:
 * брать из сети. */
int imgcache_read_start(const char *url);
/* Итог чтения: 0 — ещё идёт; 1 — готово: *body (PSRAM, теперь — вызывающего), *len и *kind
 * (IMGCACHE_FILE или IMGCACHE_PIX); −1 — не вышло (брать из сети). */
int imgcache_read_poll(uint8_t **body, size_t *len, int *kind);
/* Бросить чтение (новая страница, «стоп»). */
void imgcache_read_cancel(void);
/* Записать картинку url в кэш (запись — потом, в очереди): kind — что это (IMGCACHE_…), pre —
 * pre_len байт перед body (заголовок точек; NULL — нет), body — len байт. again = 1 — записать,
 * даже если она там уже есть («обновить», точки вместо прежнего файла). store — копией (буфер
 * остаётся у картинки), give — буфер body (PSRAM) отдаётся кэшу целиком: он его запишет и
 * освободит (или освободит сразу, если записать нельзя). Зовёт image.c, когда картинка уже
 * разобрана, — копия не мешает разбору памятью. */
void imgcache_store(const char *url, int kind, const void *pre, size_t pre_len, const uint8_t *body, size_t len,
                    int again);
void imgcache_give(const char *url, int kind, const void *pre, size_t pre_len, uint8_t *body, size_t len, int again);
/* Памяти не хватило (разбор картинки): копии в очереди на запись — прочь, идущая запись —
 * бросить (недописанный файл удалится при следующем запуске). 1 — что-то освободилось. */
int imgcache_trim(void);
/* 1 — обмен с программой Z80 о кэше идёт (новое событие E7 загрузки ей сейчас слать нельзя). */
int imgcache_busy(void);
/* Команды программы Z80 — задача обмена прошивки: 0x78 (кусок списка), 0x79 (кусок файла), а
 * 0x76/0x77 с номером операции кэша (старший бит номера, см. download.c). */
int imgcache_command(uint8_t cmd, const uint8_t *p, uint16_t n);
/* Номер операции кэша: у загрузок старший бит номера — 0, у кэша — 1. */
#define IMGCACHE_SEQ 0x8000u
#ifdef TSAFARI_HOST
/* Стенд: сколько файлов и байт в кэше, сколько прочитано с карты и записано на неё. */
void imgcache_host_stats(unsigned *files, uint32_t *bytes, unsigned *reads, unsigned *writes);
/* Стенд: предел кэша (по умолчанию 100 МБ) — проверить кольцо на малом. */
void imgcache_host_limit(uint32_t bytes);
/* Стенд: сколько байт файлов ждут записи на карту (очередь и текущая запись). */
uint32_t imgcache_host_queued(void);
#endif
