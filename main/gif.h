/* Картинки GIF: первый кадр в точки ARGB1555 для видеочипа FT812.
 *
 * GIF — старый формат (1987), на сайтах о ZX Spectrum его много: значки, кнопки, скриншоты.
 * Точка — номер цвета в палитре до 256 цветов; один номер может значить «прозрачно». Сами
 * номера сжаты алгоритмом LZW. Сопроцессор FT812 (BL616) GIF не понимает, поэтому кадр
 * раскладывает ESP32: номера → цвета палитры → 16 бит на точку ARGB1555 (1 бит прозрачности и
 * по 5 бит красного, зелёного, синего) — такой формат видеочип рисует сам, прозрачные точки
 * пропуская. Анимацию не показываем: только первый кадр. */
#pragma once
#include <stddef.h>
#include <stdint.h>

/* Это GIF? (по первым байтам «GIF87a» / «GIF89a») */
int gif_is(const uint8_t *p, size_t n);
/* Размер картинки из заголовка, 0 — не GIF. */
int gif_size(const uint8_t *p, size_t n, int *w, int *h);
/* Первый кадр в точки ARGB1555 размером не больше max_w × max_h (крупнее — уменьшается выборкой
 * ближайшей точки, пропорции сохраняются). *pix — память ts_alloc (освобождает вызвавший),
 * *ow × *oh — размер результата. 0 — испорчен или нет памяти. */
int gif_decode(const uint8_t *p, size_t n, int max_w, int max_h, uint16_t **pix, int *ow, int *oh);
