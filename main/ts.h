/* TSafari — веб-браузер для платы VDAC4 (ZX Evolution + Tang Nano 20K + ESP32-S3).
 * Этот заголовок подключают все части программы TSAFARI.ELF.
 *
 * КАК УСТРОЕН БРАУЗЕР — коротко для того, кто читает код впервые
 *
 * В браузере работают три процессора, у каждого своя часть:
 *
 *  1. Z80 компьютера ZX Evolution — программа TSAFARI.SPG (папка launcher/, ассемблер). Она
 *     находит файлы браузера на SD-карте, передаёт TSAFARI.ELF в ESP32 и дальше только
 *     пересылает в ESP32 то, что нажато на клавиатуре и мыши.
 *
 *  2. ESP32-S3 на плате VDAC4 — эта программа (папка main/, язык C). Она ходит в интернет по
 *     Wi-Fi, разбирает страницу и рисует её. TSAFARI.ELF — не прошивка, а «приложение»: файл,
 *     который прошивка ESP32 (её называют «ядром») загружает в память и запускает. Всё, что
 *     приложению нужно от прошивки (память, сеть, время, видеочип), оно получает через таблицу
 *     функций zm_core_t — указатель на неё хранится в ts_core.
 *
 *  3. Tang Nano 20K — микросхема ПЛИС, которая выводит картинку на HDMI. В режиме «Slot1» она
 *     изображает видеочип FT812 (его ещё называют EVE): ESP32 пишет в его память картинки и
 *     «дисплей-лист» — список команд рисования, а видеочип сам рисует по нему каждый кадр
 *     1024×768 точек (подробности — в ft.h).
 *
 * Как идут данные: ввод (Z80) → разбор нажатий (input.c) → действия интерфейса (ui.c) и
 * переходы (app.c) → загрузка страницы (fetch.c) → разбор HTML (html.c) → раскладка строк
 * (doc.c) → рисование строк в память видеочипа (page.c) → дисплей-лист → картинка на HDMI.
 */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include "zm_app.h"

#define TS_VERSION "0.1"

/* Размер кадра видеочипа FT812 в точках: ширина и высота. */
#define TS_W 1024
#define TS_H 768

/* Таблица функций прошивки ESP32 (её даёт прошивка при запуске приложения, app.c). */
extern const zm_core_t *ts_core;
/* 1 — браузер работает; 0 — прошивка просит остановиться: все циклы должны выйти. «volatile» —
 * значение меняют из другой задачи, компилятор не должен держать его копию в регистре. */
extern volatile int ts_running;

/* Взять память. У ESP32 два вида памяти: внутренняя (быстрая, ~300 КБ на всё) и PSRAM
 * (внешняя микросхема на 8 МБ, медленнее). Браузеру нужно много — берём PSRAM. Освобождать её
 * при выходе не обязательно: прошивка сама вернёт всё, что приложение взяло. */
void *ts_alloc(size_t bytes);
/* Строка в журнал прошивки (как printf). Журнал виден по сети: tools/read_boot.py, консоль. */
#define ts_log(...) ts_core->log(__VA_ARGS__)
