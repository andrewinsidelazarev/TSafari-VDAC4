/* Клавиатура и мышь.
 *
 * Клавиатура и мышь подключены к компьютеру ZX Evolution, а не к ESP32. Программа Z80
 * (TSAFARI.SPG) много раз в секунду читает их и пересылает в ESP32 «пакетом» — командой 0x75
 * (так же устроен DOOM VDAC4). В пакете:
 *   байт 0 — джойстик (браузеру не нужен);
 *   байт 1 — кнопки мыши (порт Kempston #FADF): биты 0–2 — кнопки, 0 = нажата; биты 7–4 —
 *            счётчик колеса;
 *   байты 2 и 3 — координаты мыши X и Y (порты #FBDF и #FFDF): это не место на экране, а
 *            счётчики 0…255, которые растут и убывают, когда мышь двигают, и проскакивают
 *            через 255 → 0. Перемещение = разность нового и прошлого значения;
 *   байты 4… — коды клавиш PS/2: клавиатура сообщает не буквы, а «скан-коды» — номера клавиш.
 *            При отпускании клавиши приходит F0 и её код, у части клавиш (стрелки и др.) перед
 *            кодом стоит E0. Буквы из номеров клавиш получаем сами, по таблицам раскладки.
 * Почему клавиатура не через матрицу ZX: так видны все клавиши PC-клавиатуры (стрелки, F1–F12,
 * Win), а AVR компьютера Evo сам копит их коды в очереди. */
#pragma once
#include <stdint.h>

/* Клавиши, которые различает браузер; KEY_CHAR — любая клавиша, дающая букву или знак. */
enum {
    KEY_NONE, KEY_CHAR, KEY_ENTER, KEY_ESC, KEY_BACKSPACE, KEY_TAB, KEY_DELETE, KEY_INSERT,
    KEY_UP, KEY_DOWN, KEY_LEFT, KEY_RIGHT, KEY_PGUP, KEY_PGDN, KEY_HOME, KEY_END, KEY_WIN,
    KEY_F1, KEY_F2, KEY_F3, KEY_F4, KEY_F5, KEY_F6, KEY_F7, KEY_F8, KEY_F9, KEY_F10, KEY_F11, KEY_F12,
};
/* «Модификаторы» — клавиши, которые зажимают вместе с другой: биты в поле mods. */
#define MOD_SHIFT 1u
#define MOD_CTRL  2u
#define MOD_ALT   4u

typedef struct {
    uint8_t key;          /* KEY_* (только нажатия; удержание — повтор клавиатуры) */
    uint8_t mods;         /* MOD_* в момент нажатия */
    uint32_t ch;          /* KEY_CHAR: символ Unicode с учётом раскладки и Shift */
} key_event_t;

typedef struct {
    int dx, dy;           /* перемещение с прошлого опроса: x вправо, y вниз (экран) */
    int wheel;            /* щелчки колеса: > 0 — от себя */
    uint8_t buttons;      /* бит 0 — левая, 1 — правая, 2 — средняя */
} mouse_state_t;

/* Подготовить ввод (до первого пакета). */
void input_init(void);
/* Принять пакет 0x75 (устройство — в начале файла). Вызывает прошивка из своей задачи обмена с Z80. */
void input_packet(const uint8_t *p, unsigned n);
/* Следующее нажатие клавиши; 0 — нажатий больше нет. Вызывает задача браузера. */
int input_key(key_event_t *ev);
/* Сколько мышь сдвинулась с прошлого вызова и какие кнопки зажаты. */
void input_mouse(mouse_state_t *m);
/* 1 — раскладка русская (Ctrl+Shift переключает). */
int input_russian(void);
