/* Интерфейс браузера поверх страницы: глобус, кнопки, строка адреса, полоса прокрутки,
 * окно Wi-Fi и курсор мыши. Внешний вид нарисовал Codex (design/DESIGN.md); все размеры,
 * цвета и таблицы анимации — в design/ui_design.h, картинки иконок — в design/ft/ui_assets.bin.
 *
 * Как ведёт себя интерфейс (решения пользователя):
 *   - в покое на экране только полупрозрачный глобус в левом верхнем углу, всё остальное место
 *     отдано странице;
 *   - курсор задержался 120 мс в «горячем углу» (квадрат 4×4 точки в самом углу) — кнопки
 *     назад, вперёд, стоп, обновить выезжают из-за левого края экрана, глобус отъезжает вправо;
 *   - щелчок по глобусу или клавиша Win — строка адреса выезжает вправо из-под глобуса;
 *   - на старте, пока нет Wi-Fi, — окно подключения поверх всего.
 *
 * Интерфейс не рисует сам: он только решает, что где, и добавляет команды в дисплей-лист
 * (ui_dl) поверх страницы. Видеочип сам рисует круги, скруглённые прямоугольники и иконки. */
#pragma once
#include <stdint.h>
#include "ft.h"
#include "input.h"

/* Что пользователь сделал — ответ ui_mouse и ui_key для app.c: «ничего», нажал назад, вперёд,
 * стоп, обновить, «перейти» (Enter или кнопка в строке адреса), настройки, щелчок по странице. */
enum { UI_NONE, UI_BACK, UI_FORWARD, UI_STOP, UI_RELOAD, UI_GO, UI_SETTINGS, UI_CLICK, UI_DL_CANCEL };
/* Состояния окна Wi-Fi: закрыто, идёт подключение, подключиться не удалось. */
enum { UI_WIFI_OFF, UI_WIFI_CONNECTING, UI_WIFI_FAILED };

/* Положить картинки интерфейса в память видеочипа. 0 — нет памяти или связи. */
int ui_init(void);
/* Курсор и кнопки мыши (pressed — нажатия с прошлого вызова, held — удерживаемые).
 * UI_CLICK — щелчок по странице, иначе действие или UI_NONE. */
int ui_mouse(int x, int y, uint8_t pressed, uint8_t held);
/* Клавиша: действие; *used = 0 — интерфейс её не взял (её разбирает страница). */
int ui_key(const key_event_t *ev, int *used);
/* Сдвинуть анимации на время now (мс, раз в кадр); 1 — картинка изменилась, нужен новый лист. */
int ui_tick(uint32_t now);
/* Идёт сетевая работа: глобус вращается (это и есть индикатор загрузки). */
void ui_set_busy(int busy);
/* Есть ли куда идти назад и вперёд по истории (иначе кнопки серые). */
void ui_set_history(int can_back, int can_forward);
/* Положение страницы для полосы прокрутки; moved — прокрутка была (полоса появляется). */
void ui_set_scroll(int top, int height, int moved);
/* Окно Wi-Fi на старте: UI_WIFI_OFF — закрыто. Пока открыто, страница не видна, кнопки отключены. */
void ui_wifi(int state);
/* 1 — окно Wi-Fi сейчас на экране. */
int ui_wifi_open(void);
/* Записать адрес в строку (UTF-8) / забрать то, что там набрано. */
void ui_set_url(const char *utf8);
const char *ui_url(void);
/* Где сейчас курсор мыши (точки экрана). */
int ui_cursor_x(void);
int ui_cursor_y(void);
/* Курсор над ссылкой страницы: заливка курсора — цветом темы (решение пользователя). */
void ui_set_link_hover(int on);
/* 1 — курсор над элементом интерфейса (кнопкой, строкой адреса, индикатором), а не над страницей. */
int ui_pointer_on_ui(void);
/* Индикатор скачивания внизу слева (дизайн Codex, п. 16). kind — TSA_UI_DOWNLOAD_KNOWN,
 * …_UNKNOWN, …_WRITING, …_DONE, …_ERROR, …_CANCELLED или −1 (нет скачивания). title — имя файла,
 * line — вторая строка (путь, текст ошибки; NULL — по kind), done/total — байты для полосы,
 * since — когда началось это состояние: готово и ошибки уходят сами через время из дизайна или
 * по щелчку, и то же состояние больше не показывается. */
void ui_download(int kind, const char *title, const char *line, uint32_t done, uint32_t total, uint32_t since);
/* Добавить в дисплей-лист команды интерфейса — после страницы, чтобы лечь поверх неё. */
void ui_dl(ft_dl_t *d);
